// Funzione base
function changeLanguage(langCode) {
    if (!dict[langCode]) langCode = 'en'; // fallback base
    const langData = dict[langCode] || dict['en'];
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (langData[key]) el.innerHTML = langData[key];
    });
    
    document.getElementById('current-lang').innerText = langCode.toUpperCase();
    localStorage.setItem('ares_lang', langCode);
    document.getElementById('lang-dropdown').classList.remove('active');
}

