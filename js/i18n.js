// Funzione base
function changeLanguage(langCode) {
    if (!dict[langCode]) langCode = 'en'; // fallback base
    const langData = dict[langCode] || dict['en'];
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (langData[key]) el.innerHTML = langData[key];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (langData[key]) el.placeholder = langData[key];
    });

    document.getElementById('current-lang').innerText = langCode.toUpperCase();
    localStorage.setItem('ares_lang', langCode);
    document.getElementById('lang-dropdown').classList.remove('active');
}

// Inizializzazione al caricamento
document.addEventListener('DOMContentLoaded', () => {
    // Lingua predefinita impostata a 'en' (inglese) come fallback primario
    const savedLang = localStorage.getItem('ares_lang') || 'en';
    changeLanguage(savedLang);

    document.getElementById('lang-btn').addEventListener('click', (e) => {
        e.stopPropagation();
        document.getElementById('lang-dropdown').classList.toggle('active');
    });

    document.addEventListener('click', () => {
        document.getElementById('lang-dropdown').classList.remove('active');
    });
});